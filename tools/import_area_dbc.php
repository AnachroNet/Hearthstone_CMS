#!/usr/bin/env php
<?php
/**
 * Build area_dbc import SQL from AreaTable.dbc (WotLK 3.3.5a).
 *
 * Usage (from project root):
 *   php tools/import_area_dbc.php [path/to/output.sql]
 *
 * Default output: SQL/Hearthstone_DATABASE/generated/area_dbc_import.sql
 */

declare(strict_types=1);

if (PHP_SAPI !== 'cli') {
    fwrite(STDERR, "Run from the command line: php tools/import_area_dbc.php\n");
    exit(1);
}

$projectRoot = dirname(__DIR__);
require_once $projectRoot . DIRECTORY_SEPARATOR . 'includes' . DIRECTORY_SEPARATOR . 'dbc_reader.php';
require_once $projectRoot . DIRECTORY_SEPARATOR . 'includes' . DIRECTORY_SEPARATOR . 'area_dbc.php';

$defaultOut = $projectRoot
    . DIRECTORY_SEPARATOR . 'SQL'
    . DIRECTORY_SEPARATOR . 'Hearthstone_DATABASE'
    . DIRECTORY_SEPARATOR . 'generated'
    . DIRECTORY_SEPARATOR . 'area_dbc_import.sql';

$outputPath = isset($argv[1]) && $argv[1] !== ''
    ? $argv[1]
    : $defaultOut;

$dbcDir = sahtout_data_dbc_dir();
if ($dbcDir === null) {
    fwrite(STDERR, "data/dbc directory not found under {$projectRoot}\n");
    exit(1);
}

$areaPath = sahtout_find_dbc_file($dbcDir, 'AreaTable.dbc');
if ($areaPath === null) {
    fwrite(STDERR, "Missing AreaTable.dbc in {$dbcDir}\n");
    exit(1);
}

try {
    $rows = sahtout_area_dbc_parse_file($areaPath);
} catch (Throwable $e) {
    fwrite(STDERR, 'Failed to read AreaTable.dbc: ' . $e->getMessage() . "\n");
    exit(1);
}

if ($rows === []) {
    fwrite(STDERR, "No area rows parsed from AreaTable.dbc\n");
    exit(1);
}

$escape = static function (string $value): string {
    return str_replace(['\\', "'"], ['\\\\', "\\'"], $value);
};

$lines = [];
$lines[] = '-- Generated by tools/import_area_dbc.php — do not edit by hand.';
$lines[] = '-- Source: ' . basename($areaPath) . ' (' . count($rows) . ' areas)';
$lines[] = '';
$lines[] = 'CREATE TABLE IF NOT EXISTS `area_dbc` (';
$lines[] = "  `area_id` smallint unsigned NOT NULL,";
$lines[] = "  `area_name` varchar(128) CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci NOT NULL,";
$lines[] = "  `map_id` smallint unsigned NOT NULL DEFAULT '0',";
$lines[] = '  PRIMARY KEY (`area_id`)';
$lines[] = ") ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;";
$lines[] = '';
$lines[] = 'TRUNCATE TABLE `area_dbc`;';
$lines[] = '';

$valueParts = [];
foreach ($rows as $row) {
    $valueParts[] = sprintf(
        '(%d,\'%s\',%d)',
        $row['area_id'],
        $escape($row['area_name']),
        $row['map_id']
    );
}

$chunkSize = 40;
foreach (array_chunk($valueParts, $chunkSize) as $chunk) {
    $lines[] = 'INSERT INTO `area_dbc` (`area_id`, `area_name`, `map_id`) VALUES';
    $lines[] = implode(",\n", $chunk) . ';';
    $lines[] = '';
}

$outDir = dirname($outputPath);
if (!is_dir($outDir) && !mkdir($outDir, 0755, true) && !is_dir($outDir)) {
    fwrite(STDERR, "Cannot create output directory: {$outDir}\n");
    exit(1);
}

$sql = implode("\n", $lines);
if (file_put_contents($outputPath, $sql) === false) {
    fwrite(STDERR, "Failed to write {$outputPath}\n");
    exit(1);
}

fwrite(STDOUT, "Wrote " . count($rows) . " areas to {$outputPath}\n");
