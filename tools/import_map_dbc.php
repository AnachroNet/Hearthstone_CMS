#!/usr/bin/env php
<?php
/**
 * Build map_dbc import SQL from Map.dbc (WotLK 3.3.5a).
 *
 * Usage (from project root):
 *   php tools/import_map_dbc.php [path/to/output.sql]
 *
 * Default output: SQL/Hearthstone_DATABASE/generated/map_dbc_import.sql
 */

declare(strict_types=1);

if (PHP_SAPI !== 'cli') {
    fwrite(STDERR, "Run from the command line: php tools/import_map_dbc.php\n");
    exit(1);
}

$projectRoot = dirname(__DIR__);
require_once $projectRoot . DIRECTORY_SEPARATOR . 'includes' . DIRECTORY_SEPARATOR . 'dbc_reader.php';
require_once $projectRoot . DIRECTORY_SEPARATOR . 'includes' . DIRECTORY_SEPARATOR . 'map_dbc.php';

$defaultOut = $projectRoot
    . DIRECTORY_SEPARATOR . 'SQL'
    . DIRECTORY_SEPARATOR . 'Hearthstone_DATABASE'
    . DIRECTORY_SEPARATOR . 'generated'
    . DIRECTORY_SEPARATOR . 'map_dbc_import.sql';

$outputPath = isset($argv[1]) && $argv[1] !== ''
    ? $argv[1]
    : $defaultOut;

$dbcDir = sahtout_data_dbc_dir();
if ($dbcDir === null) {
    fwrite(STDERR, "data/dbc directory not found under {$projectRoot}\n");
    exit(1);
}

$mapPath = sahtout_find_dbc_file($dbcDir, 'Map.dbc');
if ($mapPath === null) {
    fwrite(STDERR, "Missing Map.dbc in {$dbcDir}\n");
    exit(1);
}

try {
    $rows = sahtout_map_dbc_parse_file($mapPath);
} catch (Throwable $e) {
    fwrite(STDERR, 'Failed to read Map.dbc: ' . $e->getMessage() . "\n");
    exit(1);
}

if ($rows === []) {
    fwrite(STDERR, "No map rows parsed from Map.dbc\n");
    exit(1);
}

$escape = static function (string $value): string {
    return str_replace(['\\', "'"], ['\\\\', "\\'"], $value);
};

$lines = [];
$lines[] = '-- Generated by tools/import_map_dbc.php — do not edit by hand.';
$lines[] = '-- Source: ' . basename($mapPath) . ' (' . count($rows) . ' maps)';
$lines[] = '';
$lines[] = 'CREATE TABLE IF NOT EXISTS `map_dbc` (';
$lines[] = "  `map_id` smallint unsigned NOT NULL,";
$lines[] = "  `map_name` varchar(128) CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci NOT NULL,";
$lines[] = "  `map_type` tinyint unsigned NOT NULL DEFAULT '0',";
$lines[] = "  `max_players` smallint unsigned NOT NULL DEFAULT '0',";
$lines[] = '  PRIMARY KEY (`map_id`)';
$lines[] = ") ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;";
$lines[] = '';
$lines[] = 'TRUNCATE TABLE `map_dbc`;';
$lines[] = '';

$valueParts = [];
foreach ($rows as $row) {
    $valueParts[] = sprintf(
        '(%d,\'%s\',%d,%d)',
        $row['map_id'],
        $escape($row['map_name']),
        $row['map_type'],
        $row['max_players']
    );
}

$chunkSize = 40;
foreach (array_chunk($valueParts, $chunkSize) as $chunk) {
    $lines[] = 'INSERT INTO `map_dbc` (`map_id`, `map_name`, `map_type`, `max_players`) VALUES';
    $lines[] = implode(",\n", $chunk) . ';';
    $lines[] = '';
}

$outDir = dirname($outputPath);
if (!is_dir($outDir) && !mkdir($outDir, 0755, true) && !is_dir($outDir)) {
    fwrite(STDERR, "Cannot create output directory: {$outDir}\n");
    exit(1);
}

$sql = implode("\n", $lines);
if (file_put_contents($outputPath, $sql) === false) {
    fwrite(STDERR, "Failed to write {$outputPath}\n");
    exit(1);
}

fwrite(STDOUT, "Wrote " . count($rows) . " maps to {$outputPath}\n");
