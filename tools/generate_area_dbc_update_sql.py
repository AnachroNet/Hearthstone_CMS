#!/usr/bin/env python3
"""Build area_dbc release SQL from languages/en/playermap_zones.php (English v1 seed)."""

from __future__ import annotations

import re
import sys
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parents[1]
ZONES_FILE = PROJECT_ROOT / "languages" / "en" / "playermap_zones.php"
DEFAULT_OUT = (
    PROJECT_ROOT
    / "SQL"
    / "Hearthstone_DATABASE"
    / "UPDATES"
    / "2026111003-area-dbc.sql"
)


def parse_zones(text: str) -> list[tuple[int, str]]:
    pattern = re.compile(r"(\d+)\s*=>\s*'((?:[^'\\]|\\.)*)'")
    zones: list[tuple[int, str]] = []
    for match in pattern.finditer(text):
        zid = int(match.group(1))
        name = match.group(2).replace("\\'", "'")
        zones.append((zid, name))
    zones.sort(key=lambda pair: pair[0])
    return zones


def sql_escape(value: str) -> str:
    return value.replace("\\", "\\\\").replace("'", "\\'")


def build_sql(zones: list[tuple[int, str]], release: str) -> str:
    lines: list[str] = [
        "-- Hearthstone CMS v1.1 release " + release + " — playermap area names (English)",
        "-- Run against your site database (hearthstone_site).",
        "",
        "-- Generated by tools/generate_area_dbc_update_sql.py from languages/en/playermap_zones.php",
        f"-- Source row count: {len(zones)}",
        "",
        "CREATE TABLE IF NOT EXISTS `area_dbc` (",
        "  `area_id` smallint unsigned NOT NULL,",
        "  `area_name` varchar(128) CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci NOT NULL,",
        "  `map_id` smallint unsigned NOT NULL DEFAULT '0',",
        "  PRIMARY KEY (`area_id`)",
        ") ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;",
        "",
        "TRUNCATE TABLE `area_dbc`;",
        "",
    ]
    chunk: list[str] = []
    chunk_size = 40

    def flush_chunk() -> None:
        nonlocal chunk
        if not chunk:
            return
        lines.append("INSERT INTO `area_dbc` (`area_id`, `area_name`, `map_id`) VALUES")
        lines.append(",\n".join(chunk) + ";")
        lines.append("")
        chunk = []

    for zid, name in zones:
        esc = sql_escape(name)
        chunk.append(f"({zid},'{esc}',0)")
        if len(chunk) >= chunk_size:
            flush_chunk()
    flush_chunk()

    lines.extend(
        [
            "INSERT INTO `site_settings` (",
            "  `setting_key`, `setting_value`, `value_type`, `category`, `label`, `is_public`, `updated_by`",
            ") VALUES",
            f"  ('site.release', '{release}', 'int', 'general', 'Applied CMS release', 0, NULL)",
            "ON DUPLICATE KEY UPDATE",
            "  `setting_value` = VALUES(`setting_value`),",
            "  `value_type` = VALUES(`value_type`),",
            "  `label` = VALUES(`label`),",
            "  `is_public` = VALUES(`is_public`);",
            "",
        ]
    )
    return "\n".join(lines)


def main() -> int:
    out_path = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_OUT
    if not ZONES_FILE.is_file():
        print(f"Missing {ZONES_FILE}", file=sys.stderr)
        return 1
    text = ZONES_FILE.read_text(encoding="utf-8")
    zones = parse_zones(text)
    if not zones:
        print("No zones parsed", file=sys.stderr)
        return 1
    sql = build_sql(zones, "2026111003")
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(sql, encoding="utf-8", newline="\n")
    print(f"Wrote {len(zones)} areas to {out_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
